function pct(label: string, pick: (line: StatementLine) => number | null, emphasize?: 1 | 2, info?: string): Metric {
  return { label, format: "percent", emphasize, info, value: (line) => pick(line) };
}

function formatMetric(value: number | null, format: Format, currency: string) {
  if (value == null || Number.isNaN(value)) {
    return "—";
  }
  if (format === "percent" || format === "signed") {
    const sign = format === "signed" && value > 0 ? "+" : value < 0 ? "−" : "";
    return `${sign}${Math.abs(value).toFixed(1)}%`;
  }
  if (format === "ratio") {
    return `${value < 0 ? "−" : ""}${Math.abs(value).toFixed(2)}`;
  }
  if (format === "multiple") {
    return `${value < 0 ? "−" : ""}${Math.abs(value).toFixed(2)}×`;
  }
  if (format === "eps") {
    return formatPrice(value, currency) ?? "—";
  }
  if (format === "shares") {
    return new Intl.NumberFormat("en-US", { notation: "compact", maximumFractionDigits: 2 }).format(value);
  }
  const abs = Math.abs(value);
  const formatted = new Intl.NumberFormat("en-US", { style: "currency", currency, notation: "compact", maximumFractionDigits: 1 }).format(abs);
  return value < 0 ? `−${formatted}` : formatted;
}

function ratio(numer: number | null, denom: number | null) {
  if (numer == null || denom == null || denom === 0) {
    return null;
  }
  return numer / denom;
}

function percentOf(numer: number | null, denom: number | null) {
  const value = ratio(numer, denom);
  return value == null ? null : value * 100;
}

function change(current: number | null, previous: number | null) {
  if (current == null || previous == null || previous === 0) {
    return null;
  }
  return ((current - previous) / Math.abs(previous)) * 100;
}

function roic(line: StatementLine, scale: number) {
  const operating = line.income.operatingIncome;
  const tax = line.income.incomeTax;
  const pretax = line.income.incomeBeforeTax;
  const invested = add(line.balance.totalDebt, line.balance.equity);
  if (operating == null || tax == null || pretax == null || pretax === 0 || invested == null || invested === 0) {
    return null;
  }
  return ((operating * (1 - tax / pretax) * scale) / invested) * 100;
}

function perShare(value: number | null, line: StatementLine) {
  const shares = line.income.dilutedShares;
  if (value == null || shares == null || shares === 0) {
    return null;
  }
  return value / shares;
}

function netCash(line: StatementLine) {
  if (line.balance.cashAndInvestments == null || line.balance.totalDebt == null) {
    return null;
  }
  return line.balance.cashAndInvestments - line.balance.totalDebt;
}

function returned(line: StatementLine) {
  const dividends = line.cashFlow.dividendsPaid == null ? null : Math.abs(line.cashFlow.dividendsPaid);
  const buybacks = line.cashFlow.shareRepurchases == null ? null : Math.abs(line.cashFlow.shareRepurchases);
  return add(dividends, buybacks);
}

function outflow(value: number | null) {
  if (value == null) {
    return null;
  }
  return -Math.abs(value);
}

function scaled(value: number | null, scale: number) {
  return value == null ? null : value * scale;
}

function minus(left: number | null, right: number | null) {
  if (left == null || right == null) {
    return null;
  }
  return left - right;
}

function add(left: number | null, right: number | null) {
  if (left == null) {
    return right;
  }
  if (right == null) {
    return left;
  }
  return left + right;
}

