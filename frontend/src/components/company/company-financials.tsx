"use client";

import type { MouseEvent, ReactNode } from "react";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { useEffect, useState } from "react";
import { Info } from "lucide-react";
import { CompanyIdentity } from "@/components/company/company-identity";
import { CompanySkeleton } from "@/components/company/company-skeleton";
import {
  formatPrice,
  getCompanyStatements,
  getInstrument,
  instrumentFullFinancialsPath,
  instrumentPath,
  type CompanyProfile,
  type CompanyStatements,
  type StatementLine,
  type StatementPeriod,
} from "@/lib/instruments";

const INFO: Record<string, { title: string; text: string }> = {
  opInc: { title: "Operating income", text: "Profit from the core business, before interest and taxes." },
  capex: { title: "Capital expenditures", text: "Money spent on long-lasting assets like equipment and facilities." },
  fcf: { title: "Free cash flow", text: "Cash generated by the business after capital expenditures." },
  eq: { title: "Shareholders’ equity", text: "What would be left for owners if all liabilities were paid." },
  epsD: { title: "Diluted EPS", text: "Profit per share, counting shares that options could still create." },
  fm: { title: "FCF margin", text: "Free cash flow as a share of revenue." },
};

type RowDef = {
  group?: string;
  label?: string;
  pick?: (line: StatementLine) => number | null;
  format?: "money" | "eps" | "percent";
  emphasize?: 1 | 2;
  detail?: boolean;
  info?: string;
  outflow?: boolean;
};

export function CompanyFinancials({ symbol }: { symbol: string }) {
  const router = useRouter();
  const [company, setCompany] = useState<CompanyProfile | null>(null);
  const [annual, setAnnual] = useState<CompanyStatements | null>(null);
  const [quarterly, setQuarterly] = useState<CompanyStatements | null>(null);
  const [period, setPeriod] = useState<StatementPeriod>("ANNUAL");
  const [range, setRange] = useState(5);
  const [error, setError] = useState<string | null>(null);
  const [filingsError, setFilingsError] = useState<string | null>(null);
  const [loading, setLoading] = useState(true);
  const [full, setFull] = useState<Record<string, boolean>>({});
  const [active, setActive] = useState("fin-perf");
  const [info, setInfo] = useState<{ key: string; x: number; y: number } | null>(null);
  const [switching, setSwitching] = useState(false);
  const [quarterlyNote, setQuarterlyNote] = useState<string | null>(null);

  useEffect(() => {
    const controller = new AbortController();
    (async () => {
      setLoading(true);
      setError(null);
      setFilingsError(null);
      setAnnual(null);
      setQuarterly(null);
      try {
        const profile = await getInstrument(symbol);
        if (controller.signal.aborted) {
          return;
        }
        if (profile.symbol && profile.symbol.toUpperCase() !== symbol.trim().toUpperCase()) {
          router.replace(`${instrumentPath(profile.symbol)}/financials`);
        }
        setCompany(profile);
        setLoading(false);
        try {
          const year = await getCompanyStatements(profile.symbol, "ANNUAL", controller.signal);
          if (controller.signal.aborted) {
            return;
          }
          setAnnual(year);
        } catch (err) {
          if (controller.signal.aborted || (err instanceof DOMException && err.name === "AbortError")) {
            return;
          }
          setFilingsError(err instanceof Error ? err.message : "Could not load filings.");
        }
      } catch (err) {
        if (controller.signal.aborted || (err instanceof DOMException && err.name === "AbortError")) {
          return;
        }
        setError(err instanceof Error ? err.message : "Could not load this company.");
        setLoading(false);
      }
    })();
    return () => controller.abort();
  }, [symbol, router]);

  useEffect(() => {
    function onScroll() {
      const ids = ["fin-perf", "fin-is", "fin-bs", "fin-cf", "fin-mg"];
      let current = ids[0];
      for (const id of ids) {
        const el = document.getElementById(id);
        if (el && el.getBoundingClientRect().top < 140) {
          current = id;
        }
      }
      setActive(current);
    }
    window.addEventListener("scroll", onScroll, { passive: true });
    return () => window.removeEventListener("scroll", onScroll);
  }, []);

  const usingQuarterly = period === "QUARTERLY" && Boolean(quarterly);
  const statements = usingQuarterly ? quarterly : annual;
  const lines = statements?.lines ?? [];
  const available = Math.min(10, lines.length);
  const count = Math.min(range, available);
  const slice = lines.slice(-count);
  const newest = [...slice].reverse();
  const currency = statements?.currency ?? company?.currency ?? "USD";
  const displayName = company?.name.replace(/\s+Inc\.?$/i, "").trim() || company?.name || "";
  const lag = usingQuarterly && lines.length >= 8 ? 4 : 1;
  const deltaLabel = usingQuarterly && lag === 1 ? "QoQ" : "YoY";
  const canTen = available > 5;
  const unit = usingQuarterly ? "fiscal quarters" : "fiscal years";

  if (loading) {
    return <CompanySkeleton />;
  }

  if (error || !company) {
    return (
      <div className="px-4 py-10 sm:px-10 sm:py-14">
        <h1 className="text-[28px] font-light tracking-tight text-[#ECECE8]">Company not found</h1>
        <p className="mt-3 max-w-[46ch] text-[15px] leading-relaxed text-muted">
          {error ?? "We could not find that company."} Search the company name and pick the main listing.
        </p>
      </div>
    );
  }

  const filingsReady = annual != null || filingsError != null;
  if (!filingsReady) {
    return (
      <div className="mx-auto flex w-full max-w-[1320px] flex-col gap-7 px-4 pb-12 pt-3 sm:px-10">
        <CompanyIdentity company={company} tab="financials" />
        <p className="text-[15px] text-dim">Loading filings…</p>
      </div>
    );
  }

  if (filingsError || slice.length < 1) {
    return (
      <div className="mx-auto flex w-full max-w-[1320px] flex-col gap-7 px-4 pb-12 pt-3 sm:px-10">
        <CompanyIdentity company={company} tab="financials" />
        <p className="text-[15px] text-dim">{filingsError ?? "No filed financials yet for this company."}</p>
      </div>
    );
  }

  const last = slice[slice.length - 1];
  const prevIndex = slice.length - 1 - lag;
  const prev = prevIndex >= 0 ? slice[prevIndex] : null;
  const lastE = enrich(last);
  const prevE = prev ? enrich(prev) : null;

  const highlights = (
    [
      ["Revenue", lastE.revenue, prevE?.revenue, "money"],
      ["Net income", lastE.netIncome, prevE?.netIncome, "money"],
      ["EPS (diluted)", lastE.epsDiluted ?? lastE.eps, prevE?.epsDiluted ?? prevE?.eps, "eps"],
      ["Free cash flow", lastE.freeCashFlow, prevE?.freeCashFlow, "money"],
      ["Operating cash flow", lastE.operatingCashFlow, prevE?.operatingCashFlow, "money"],
      ["Cash & investments", lastE.cashAndInvestments, prevE?.cashAndInvestments, "money", true],
      ["Total debt", lastE.totalDebt, prevE?.totalDebt, "money", true],
    ] as const
  )
    .map(([label, value, previous, format, stock]) => {
      const yoy = growth(value, previous);
      return {
        label,
        value: format === "eps" ? formatPrice(value, currency) : money(value, currency),
        yoy,
        stock: Boolean(stock),
      };
    })
    .filter((row) => row.value);

  const perf = (
    [
      ["Revenue", (line: Enriched) => line.revenue],
      ["Net income", (line: Enriched) => line.netIncome],
      ["Free cash flow", (line: Enriched) => line.freeCashFlow],
    ] as const
  ).map(([label, pick]) => series(label, slice.map(enrich), pick, currency, usingQuarterly ? "QUARTERLY" : "ANNUAL", count));

  const incomeRows: RowDef[] = [
    { group: "Revenue" },
    { label: "Revenue", pick: (l) => l.income.revenue, emphasize: 1 },
    { label: "Cost of revenue", pick: (l) => l.income.costOfRevenue },
    { label: "Gross profit", pick: (l) => l.income.grossProfit },
    { group: "Operating" },
    { label: "Operating expenses", pick: (l) => l.income.operatingExpenses },
    { label: "Research & development", pick: (l) => l.income.researchAndDevelopment, detail: true },
    { label: "Selling, general & admin", pick: (l) => l.income.sellingGeneralAndAdmin, detail: true },
    { label: "Operating income", pick: (l) => l.income.operatingIncome, emphasize: 1, info: "opInc" },
    { label: "EBITDA", pick: (l) => l.income.ebitda, detail: true },
    { group: "Earnings" },
    { label: "Interest / other income", pick: (l) => l.income.interestAndOther },
    { label: "Income before tax", pick: (l) => l.income.incomeBeforeTax },
    { label: "Income tax", pick: (l) => l.income.incomeTax },
    { label: "Effective tax rate", pick: (l) => taxRate(l), format: "percent", detail: true },
    { label: "Net income", pick: (l) => l.income.netIncome, emphasize: 1 },
    { group: "Per share" },
    { label: "EPS", pick: (l) => l.income.eps, format: "eps" },
    { label: "Diluted EPS", pick: (l) => l.income.epsDiluted, format: "eps", info: "epsD" },
  ];
  const balanceRows: RowDef[] = [
    { group: "Assets" },
    { label: "Cash & cash equivalents", pick: (l) => l.balance.cash },
    { label: "Short-term investments", pick: (l) => l.balance.shortTermInvestments },
    { label: "Total current assets", pick: (l) => l.balance.totalCurrentAssets },
    { label: "Long-term investments", pick: (l) => l.balance.longTermInvestments, detail: true },
    { label: "Total assets", pick: (l) => l.balance.totalAssets, emphasize: 1 },
    { group: "Liabilities" },
    { label: "Short-term debt", pick: (l) => l.balance.shortTermDebt },
    { label: "Long-term debt", pick: (l) => l.balance.longTermDebt },
    { label: "Total debt", pick: (l) => l.balance.totalDebt, detail: true },
    { label: "Total current liabilities", pick: (l) => l.balance.totalCurrentLiabilities, detail: true },
    { label: "Total liabilities", pick: (l) => l.balance.totalLiabilities, emphasize: 1 },
    { group: "Equity" },
    { label: "Shareholders’ equity", pick: (l) => l.balance.equity, emphasize: 1, info: "eq" },
    { label: "Net cash (cash & investments − debt)", pick: (l) => netCash(l), detail: true },
  ];
  const cashRows: RowDef[] = [
    { group: "Operations" },
    { label: "Operating cash flow", pick: (l) => l.cashFlow.operatingCashFlow, emphasize: 1 },
    { label: "Stock-based compensation", pick: (l) => l.cashFlow.stockBasedCompensation, detail: true },
    { label: "Depreciation & amortization", pick: (l) => l.cashFlow.depreciationAndAmortization, detail: true },
    { label: "Capital expenditures", pick: (l) => l.cashFlow.capex, outflow: true, info: "capex" },
    { label: "Free cash flow", pick: (l) => l.cashFlow.freeCashFlow, emphasize: 2, info: "fcf" },
    { group: "Returned to shareholders" },
    { label: "Dividends paid", pick: (l) => l.cashFlow.dividendsPaid, outflow: true },
    { label: "Share repurchases", pick: (l) => l.cashFlow.shareRepurchases, outflow: true },
    { group: "Other flows" },
    { label: "Investing cash flow", pick: (l) => l.cashFlow.investingCashFlow },
    { label: "Financing cash flow", pick: (l) => l.cashFlow.financingCashFlow },
    { label: "Net change in cash", pick: (l) => l.cashFlow.netChangeInCash, detail: true },
  ];

  const marginSeries = [
    { label: "Gross margin", color: "#8E9CE0", pick: (line: Enriched) => line.grossMargin, info: undefined },
    { label: "Operating margin", color: "#C9CBC6", pick: (line: Enriched) => line.operatingMargin, info: undefined },
    { label: "Net margin", color: "#6FA8B8", pick: (line: Enriched) => line.netMargin, info: undefined },
    { label: "FCF margin", color: "#B49ADB", pick: (line: Enriched) => line.fcfMargin, info: "fm" },
  ];
  const marginValues = slice.map(enrich).flatMap((line) => marginSeries.map((series) => series.pick(line)).filter((value): value is number => value != null));
  const mMin = marginValues.length ? Math.floor((Math.min(...marginValues) - 2) / 5) * 5 : 0;
  const mMax = marginValues.length ? Math.ceil((Math.max(...marginValues) + 2) / 5) * 5 : 50;
  const mSpan = mMax - mMin || 1;

  const growthRows = [
    ["Revenue growth", (line: Enriched) => line.revenue],
    ["Net income growth", (line: Enriched) => line.netIncome],
    ["EPS growth", (line: Enriched) => line.epsDiluted ?? line.eps],
    ["Free cash flow growth", (line: Enriched) => line.freeCashFlow],
  ] as const;

  const infoCard = info ? INFO[info.key] : null;
  const columns = `minmax(210px,1.7fr) repeat(${newest.length}, minmax(70px,1fr))`;
  const anchors = [
    ["fin-perf", "Financial performance"],
    ["fin-is", "Income statement"],
    ["fin-bs", "Balance sheet"],
    ["fin-cf", "Cash flow"],
    ["fin-mg", "Margins & growth"],
  ] as const;

  async function showQuarterly() {
    if (!company) {
      return;
    }
    if (quarterly) {
      setPeriod("QUARTERLY");
      setQuarterlyNote(null);
      return;
    }
    setSwitching(true);
    setQuarterlyNote(null);
    try {
      const quarter = await getCompanyStatements(company.symbol, "QUARTERLY");
      if (quarter.lines.length >= 2) {
        setQuarterly(quarter);
        setPeriod("QUARTERLY");
      } else {
        setQuarterlyNote("Quarterly filings aren’t available for this listing.");
      }
    } catch (err) {
      setQuarterlyNote(err instanceof Error ? err.message : "Could not load quarterly filings.");
    } finally {
      setSwitching(false);
    }
  }

  function go(id: string) {
    const el = document.getElementById(id);
    if (el) {
      window.scrollTo({ top: el.getBoundingClientRect().top + window.scrollY - 64, behavior: "smooth" });
    }
    setActive(id);
  }

  return (
    <div className="mx-auto flex w-full max-w-[1320px] flex-col gap-7 px-4 pb-12 pt-3 sm:px-10">
      <CompanyIdentity company={company} tab="financials" />

      <div className="flex flex-wrap items-end gap-x-6 gap-y-4">
        <div className="min-w-0 flex-[1_1_360px]">
          <h2 className="text-[22px] font-normal tracking-[-0.015em] text-[#ECECE8]">Financials</h2>
          <p className="mt-1.5 text-sm text-[#8A9199]">Explore {displayName}’s financial performance and how it has evolved over time.</p>
          <Link href={instrumentFullFinancialsPath(company.symbol)} className="mt-2 inline-flex text-[13px] font-medium text-link hover:text-link-hover">
            Full financial data
          </Link>
        </div>
        <div className="flex flex-wrap gap-2.5">
          <Seg>
            <SegBtn
              active={!usingQuarterly}
              onClick={() => {
                setPeriod("ANNUAL");
                setQuarterlyNote(null);
              }}
            >
              Annual
            </SegBtn>
            <SegBtn active={period === "QUARTERLY"} onClick={showQuarterly}>
              {switching ? "Loading" : "Quarterly"}
            </SegBtn>
          </Seg>
          {canTen ? (
            <Seg>
              <SegBtn active={range === 5} onClick={() => setRange(5)}>
                {usingQuarterly ? "5Q" : "5Y"}
              </SegBtn>
              <SegBtn active={range === 10} onClick={() => setRange(10)}>
                {usingQuarterly ? "10Q" : "10Y"}
              </SegBtn>
            </Seg>
          ) : null}
        </div>
        {quarterlyNote ? <p className="w-full text-[13px] text-[#8A9199]">{quarterlyNote}</p> : null}
      </div>

      <section className="-mt-2 flex flex-col gap-3">
        <div className="flex items-baseline gap-2.5">
          <h3 className="text-[15px] font-semibold text-[#ECECE8]">Financial highlights</h3>
          <span className="text-[12.5px] text-[#6C727B]">
            {usingQuarterly
              ? `${last.label}${prev ? ` vs. ${prev.label}` : ""}`
              : `fiscal ${last.label}${prev ? ` vs. ${prev.label}` : ""}`}
          </span>
        </div>
        <div className="grid grid-cols-[repeat(auto-fit,minmax(150px,1fr))] overflow-hidden rounded-2xl bg-card">
          {highlights.map((item) => (
            <div key={item.label} className="px-5 py-[18px] shadow-[1px_0_0_#191C20,0_1px_0_#191C20]">
              <div className="text-[12.5px] text-[#7C828B]">{item.label}</div>
              <div className="mt-2 text-[21px] font-normal tracking-[-0.01em] text-[#ECECE8]">{item.value}</div>
              {item.yoy != null ? (
                <div className={`mt-1.5 text-[12.5px] font-medium ${item.stock ? "text-[#8A9199]" : item.yoy >= 0 ? "text-[#7FAE92]" : "text-[#C98A84]"}`}>
                  {signedPct(item.yoy)} {deltaLabel}
                </div>
              ) : null}
            </div>
          ))}
        </div>
      </section>

      <div className="sticky top-0 z-10 -mx-4 border-b border-[#14171A] bg-background px-4 py-2.5 sm:-mx-10 sm:px-10">
        <div className="flex flex-wrap gap-1">
          {anchors.map(([id, label]) => (
            <button
              key={id}
              type="button"
              onClick={() => go(id)}
              className={`h-[30px] rounded-lg px-3 text-[13px] ${active === id ? "bg-[#16191D] font-semibold text-[#ECECE8]" : "font-medium text-[#7C828B] hover:text-[#ECECE8]"}`}
            >
              {label}
            </button>
          ))}
        </div>
      </div>

      <section id="fin-perf" className="scroll-mt-16 rounded-2xl bg-card px-7 py-6">
        <div className="flex flex-wrap items-baseline gap-3">
          <h3 className="text-[15px] font-semibold text-[#ECECE8]">Financial performance</h3>
          <span className="text-[12.5px] text-[#6C727B]">is the business growing and generating cash?</span>
          <span className="ml-auto text-xs text-[#6C727B]">{currency}</span>
        </div>
        <div className="mt-[22px] grid grid-cols-[repeat(auto-fit,minmax(240px,1fr))] gap-x-10 gap-y-7">
          {perf.map((item) => (
            <div key={item.label}>
              <div className="flex items-baseline gap-2.5">
                <span className="text-[13px] text-[#9BA1A9]">{item.label}</span>
                <span className="ml-auto text-xs text-[#6C727B]">{item.trend}</span>
              </div>
              <div className="mt-1.5 text-[22px] font-normal tracking-[-0.01em] text-[#ECECE8]">{item.latest}</div>
              <div className={`mt-4 flex h-[120px] items-end ${count > 5 ? "gap-1.5" : "gap-2.5"}`}>
                {item.bars.map((bar, index) => (
                  <div key={bar.label} className="flex h-full min-w-0 flex-1 flex-col justify-end gap-1.5">
                    <span className="text-center text-[10.5px] whitespace-nowrap text-[#7C828B]">{bar.value}</span>
                    <div
                      className="rounded-t-[3px]"
                      style={{
                        height: `${bar.height}px`,
                        background: bar.negative ? "#6A3E3C" : index === item.bars.length - 1 ? "#8E9CE0" : "#2A3040",
                      }}
                    />
                  </div>
                ))}
              </div>
              <div className={`mt-2 flex ${count > 5 ? "gap-1.5" : "gap-2.5"}`}>
                {item.bars.map((bar) => (
                  <span key={bar.label} className="min-w-0 flex-1 text-center text-[10.5px] whitespace-nowrap text-[#6C727B]">
                    {bar.label}
                  </span>
                ))}
              </div>
            </div>
          ))}
        </div>
      </section>

      <StatementTable
        id="fin-is"
        title="Income statement"
        subtitle={`${currency} · ${unit} · except per share`}
        columns={columns}
        newest={newest}
        rows={incomeRows}
        currency={currency}
        expanded={Boolean(full["fin-is"])}
        onToggle={() => setFull((state) => ({ ...state, "fin-is": !state["fin-is"] }))}
        onInfo={(key, event) => setInfo({ key, x: event.currentTarget.getBoundingClientRect().right + 10, y: event.currentTarget.getBoundingClientRect().top - 8 })}
        onHideInfo={() => setInfo(null)}
      />
      <StatementTable
        id="fin-bs"
        title="Balance sheet"
        subtitle={`${currency} · end of period`}
        columns={columns}
        newest={newest}
        rows={balanceRows}
        currency={currency}
        expanded={Boolean(full["fin-bs"])}
        onToggle={() => setFull((state) => ({ ...state, "fin-bs": !state["fin-bs"] }))}
        onInfo={(key, event) => setInfo({ key, x: event.currentTarget.getBoundingClientRect().right + 10, y: event.currentTarget.getBoundingClientRect().top - 8 })}
        onHideInfo={() => setInfo(null)}
      />
      <StatementTable
        id="fin-cf"
        title="Cash flow"
        subtitle={`${currency} · ${unit}`}
        columns={columns}
        newest={newest}
        rows={cashRows}
        currency={currency}
        expanded={Boolean(full["fin-cf"])}
        onToggle={() => setFull((state) => ({ ...state, "fin-cf": !state["fin-cf"] }))}
        onInfo={(key, event) => setInfo({ key, x: event.currentTarget.getBoundingClientRect().right + 10, y: event.currentTarget.getBoundingClientRect().top - 8 })}
        onHideInfo={() => setInfo(null)}
      />

      <section id="fin-mg" className="scroll-mt-16 rounded-2xl bg-card px-7 py-[22px]">
        <div className="flex flex-wrap items-baseline gap-3">
          <h3 className="text-[15px] font-semibold text-[#ECECE8]">Margins</h3>
          <span className="text-[12.5px] text-[#6C727B]">share of revenue kept at each level</span>
        </div>
        <div className="mt-4 flex flex-wrap gap-x-6 gap-y-2.5">
          {marginSeries.map((series) => {
            const latest = series.pick(lastE);
            return (
              <div key={series.label} className="flex items-center gap-2 text-[13px] text-[#9BA1A9]">
                <span className="h-0.5 w-2.5 rounded-sm" style={{ background: series.color }} />
                {series.label}
                <span className="font-medium text-[#ECECE8]">{latest != null ? `${latest.toFixed(1)}%` : "—"}</span>
                {series.info ? (
                  <button
                    type="button"
                    className="text-[#5E646D] hover:text-link"
                    onMouseEnter={(event) => setInfo({ key: series.info!, x: event.currentTarget.getBoundingClientRect().right + 10, y: event.currentTarget.getBoundingClientRect().top - 8 })}
                    onMouseLeave={() => setInfo(null)}
                    aria-label={series.label}
                  >
                    <Info size={13} strokeWidth={1.8} />
                  </button>
                ) : null}
              </div>
            );
          })}
        </div>
        <div className="relative mt-[18px] h-[220px] pr-11">
          <svg viewBox="0 0 1000 220" preserveAspectRatio="none" width="100%" height="220" className="block overflow-visible">
            <line x1="0" x2="1000" y1="10" y2="10" stroke="#191C20" />
            <line x1="0" x2="1000" y1="110" y2="110" stroke="#191C20" />
            <line x1="0" x2="1000" y1="210" y2="210" stroke="#191C20" />
            {marginSeries.map((series) => {
              const points = slice.map(enrich).map((line, index) => {
                const value = series.pick(line);
                if (value == null) {
                  return null;
                }
                const x = slice.length === 1 ? 0 : (index / (slice.length - 1)) * 1000;
                const y = 210 - ((value - mMin) / mSpan) * 200;
                return `${x.toFixed(1)} ${y.toFixed(1)}`;
              });
              const d = points.reduce<string>((path, point) => {
                if (!point) {
                  return path;
                }
                return path ? `${path} L${point}` : `M${point}`;
              }, "");
              return d ? <path key={series.label} d={d} fill="none" stroke={series.color} strokeWidth="1.75" strokeLinejoin="round" /> : null;
            })}
          </svg>
          <div className="absolute top-0.5 right-0 text-[11.5px] text-[#6C727B]">{mMax}%</div>
          <div className="absolute top-[102px] right-0 text-[11.5px] text-[#6C727B]">{Math.round((mMax + mMin) / 2)}%</div>
          <div className="absolute top-[202px] right-0 text-[11.5px] text-[#6C727B]">{mMin}%</div>
        </div>
        <div className="mt-2.5 flex justify-between pr-11 text-[11px] text-[#6C727B]">
          {slice.map((line) => (
            <span key={line.label}>{line.shortLabel || line.label}</span>
          ))}
        </div>
      </section>

      <section className="rounded-2xl bg-card px-4 pt-6 pb-3.5">
        <div className="flex flex-wrap items-baseline gap-3 px-3">
          <h3 className="text-[15px] font-semibold text-[#ECECE8]">Growth</h3>
          <span className="text-[12.5px] text-[#6C727B]">
            {usingQuarterly
              ? lag === 4
                ? "change vs. the same quarter a year earlier"
                : "change vs. the prior quarter"
              : "year-over-year change"}
          </span>
        </div>
        <div className="mt-3.5 overflow-x-auto">
          <div style={{ minWidth: 210 + newest.length * 78 }}>
            <div className="grid items-end border-b border-[#1E2228] px-3 pb-2.5" style={{ gridTemplateColumns: columns }}>
              <span />
              {newest.map((line, index) => (
                <span key={line.label} className={`text-right text-xs whitespace-nowrap ${index === 0 ? "font-semibold text-[#BDC3CB]" : "font-medium text-[#6C727B]"}`}>
                  {line.label}
                </span>
              ))}
            </div>
            {growthRows.map(([label, pick]) => (
              <div key={label} className="grid items-center border-t border-[#15181B] px-3 py-2.5" style={{ gridTemplateColumns: columns }}>
                <span className="text-sm text-[#9BA1A9]">{label}</span>
                {newest.map((line, index) => {
                  const source = lines;
                  const position = source.findIndex((item) => item.label === line.label && item.date === line.date);
                  const earlier = position >= lag ? enrich(source[position - lag]) : null;
                  const value = growth(pick(enrich(line)), earlier ? pick(earlier) : null);
                  return (
                    <span key={line.label} className="flex justify-end">
                      <span
                        className={`min-w-[62px] rounded-md px-2 py-0.5 text-right text-[13px] font-medium ${
                          value == null ? "text-[#5E646D]" : value >= 0 ? "bg-[rgba(86,161,119,0.08)] text-[#8DBA9F]" : "bg-[rgba(193,96,90,0.10)] text-[#D19A94]"
                        }`}
                      >
                        {value == null ? "—" : signedPct(value)}
                      </span>
                    </span>
                  );
                })}
              </div>
            ))}
          </div>
        </div>
      </section>

      <div className="flex flex-wrap gap-x-6 gap-y-2 text-[12.5px] text-[#6C727B]">
        <span>Quantora shows the filings as reported. It doesn’t rate or score the company.</span>
        <span className="ml-auto">
          Delayed third-party data · {unit} · {currency}
        </span>
      </div>

      {infoCard ? (
        <div
          className="pointer-events-none fixed z-50 w-[250px] rounded-[10px] bg-[#1A1D22] px-3 py-2.5 shadow-[0_12px_32px_rgba(0,0,0,0.45)]"
          style={{ left: Math.min(info!.x, typeof window === "undefined" ? info!.x : window.innerWidth - 270), top: info!.y }}
        >
          <div className="text-[12.5px] font-semibold text-[#ECECE8]">{infoCard.title}</div>
          <div className="mt-1 text-[12.5px] leading-snug text-[#9BA1A9]">{infoCard.text}</div>
        </div>
      ) : null}
    </div>
  );
}

