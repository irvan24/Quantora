type Enriched = ReturnType<typeof enrich>;

function enrich(line: StatementLine) {
  const revenue = line.income.revenue;
  const gross = line.income.grossProfit ?? minus(revenue, line.income.costOfRevenue);
  const operating = line.income.operatingIncome;
  const netIncome = line.income.netIncome;
  const fcf = line.cashFlow.freeCashFlow;
  return {
    label: line.label,
    shortLabel: line.shortLabel,
    ...line.income,
    ...line.balance,
    ...line.cashFlow,
    revenue,
    grossProfit: gross,
    netIncome,
    freeCashFlow: fcf,
    grossMargin: ratioPct(gross, revenue),
    operatingMargin: ratioPct(operating, revenue),
    netMargin: ratioPct(netIncome, revenue),
    fcfMargin: ratioPct(fcf, revenue),
  };
}

function series(
  label: string,
  rows: Enriched[],
  pick: (row: Enriched) => number | null,
  currency: string,
  period: StatementPeriod,
  count: number,
) {
  const values = rows.map(pick);
  const numeric = values.filter((value): value is number => value != null);
  const max = Math.max(...numeric.map(Math.abs), 1);
  const first = numeric[0];
  const last = numeric[numeric.length - 1];
  const years = Math.max(1, numeric.length - 1);
  const trend =
    period === "ANNUAL" && first != null && last != null && first > 0 && last > 0 && numeric.length > 1
      ? `${signedPct((Math.pow(last / first, 1 / years) - 1) * 100)} / yr over ${count}y`
      : numeric.length > 1
        ? `${signedPct(growth(last, numeric[numeric.length - 2]) ?? 0)} vs. prior`
        : "";
  return {
    label,
    latest: money(last, currency),
    trend,
    bars: rows.map((row, index) => {
      const value = pick(row);
      return {
        label: row.shortLabel || row.label || String(index),
        value: value == null ? "" : compact(value, currency),
        height: value == null ? 0 : Math.max(2, Math.round((Math.abs(value) / max) * 86)),
        negative: value != null && value < 0,
      };
    }),
  };
}

function visibleRows(rows: RowDef[], expanded: boolean, newest: StatementLine[]) {
  const visible: RowDef[] = [];
  let pending: string | null = null;
  for (const row of rows) {
    if (row.group && !row.pick) {
      pending = row.group;
      continue;
    }
    if (!row.pick) {
      continue;
    }
    const shown = (expanded || !row.detail) && newest.some((line) => row.pick?.(line) != null);
    if (!shown) {
      continue;
    }
    if (pending) {
      visible.push({ group: pending });
      pending = null;
    }
    visible.push(row);
  }
  return visible;
}

function taxRate(line: StatementLine) {
  const tax = line.income.incomeTax;
  const pretax = line.income.incomeBeforeTax;
  if (tax == null || pretax == null || pretax === 0) {
    return null;
  }
  return (tax / pretax) * 100;
}

function netCash(line: StatementLine) {
  if (line.balance.cashAndInvestments == null || line.balance.totalDebt == null) {
    return null;
  }
  return line.balance.cashAndInvestments - line.balance.totalDebt;
}

function minus(left: number | null, right: number | null) {
  if (left == null || right == null) {
    return null;
  }
  return left - right;
}

function ratioPct(numer: number | null | undefined, denom: number | null | undefined) {
  if (numer == null || denom == null || denom === 0) {
    return null;
  }
  return (numer / denom) * 100;
}

function growth(current: number | null | undefined, previous: number | null | undefined) {
  if (current == null || previous == null || previous === 0) {
    return null;
  }
  return ((current - previous) / Math.abs(previous)) * 100;
}

function asOutflow(value: number | null) {
  if (value == null) {
    return null;
  }
  return -Math.abs(value);
}

function money(value: number | null | undefined, currency: string) {
  if (value == null || Number.isNaN(value)) {
    return null;
  }
  const abs = Math.abs(value);
  const formatted = new Intl.NumberFormat("en-US", {
    style: "currency",
    currency,
    notation: "compact",
    maximumFractionDigits: 1,
  }).format(abs);
  return value < 0 ? `−${formatted}` : formatted;
}

function compact(value: number, currency: string) {
  return new Intl.NumberFormat("en-US", {
    notation: "compact",
    maximumFractionDigits: 0,
    currency,
    style: "currency",
  })
    .format(value)
    .replace(/\.0$/, "");
}

function signedPct(value: number) {
  const sign = value > 0 ? "+" : value < 0 ? "−" : "";
  return `${sign}${Math.abs(value).toFixed(1)}%`;
}
